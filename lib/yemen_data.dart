class LandmarkItem {
  String title;
  String article;
  String gps;
  String videoUrl;
  String imageUrl;

  LandmarkItem({
    required this.title,
    required this.article,
    this.gps = '',
    this.videoUrl = '',
    this.imageUrl = '',
  });
}

class VillageItem {
  String name;
  String gps;
  List<LandmarkItem> landmarks;

  VillageItem(
      {required this.name, this.gps = '', List<LandmarkItem>? landmarks})
      : landmarks = landmarks ?? [];
}

class SubDistrictItem {
  String name;
  String gps;
  List<VillageItem> villages;
  List<LandmarkItem> landmarks;

  SubDistrictItem({
    required this.name,
    this.gps = '',
    List<VillageItem>? villages,
    List<LandmarkItem>? landmarks,
  })  : villages = villages ?? [],
        landmarks = landmarks ?? [];
}

class DistrictItem {
  String name;
  String gps;
  List<SubDistrictItem> subDistricts;
  List<LandmarkItem> landmarks;

  DistrictItem({
    required this.name,
    this.gps = '',
    List<SubDistrictItem>? subDistricts,
    List<LandmarkItem>? landmarks,
  })  : subDistricts = subDistricts ?? [],
        landmarks = landmarks ?? [];
}

class GovernorateItem {
  String name;
  String gps;
  List<DistrictItem> districts;
  List<LandmarkItem> landmarks;

  GovernorateItem({
    required this.name,
    this.gps = '',
    List<DistrictItem>? districts,
    List<LandmarkItem>? landmarks,
  })  : districts = districts ?? [],
        landmarks = landmarks ?? [];
}

